"""Settings dialog and TOML persistence."""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

from PySide6.QtWidgets import (
    QCheckBox,
    QDialog,
    QDialogButtonBox,
    QDoubleSpinBox,
    QFormLayout,
    QLineEdit,
    QSpinBox,
    QVBoxLayout,
)

from jarvis.config import AppConfig


def _quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _number(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def dump_config(config: AppConfig) -> str:
    """Serialize the effective configuration to TOML (used by the GUI)."""

    lines: list[str] = [
        "# Generated by the Jarvis settings window.",
        "",
        "[assistant]",
        f"name = {_quote(config.assistant.name)}",
        f"wake_word = {_quote(config.assistant.wake_word)}",
        f"wake_word_enabled = {'true' if config.assistant.wake_word_enabled else 'false'}",
        f"sensitivity = {_number(config.assistant.sensitivity)}",
        f"hotkey = {_quote(config.assistant.hotkey)}",
        f"manual_hotkey = {_quote(config.assistant.manual_hotkey)}",
        f"language = {_quote(config.assistant.language)}",
        f"data_dir = {_quote(config.assistant.data_dir)}",
        "",
        "[stt]",
        f"model = {_quote(config.stt.model)}",
        f"compute_type = {_quote(config.stt.compute_type)}",
        f"device = {_quote(config.stt.device)}",
        f"language = {_quote(config.stt.language)}",
        f"beam_size = {config.stt.beam_size}",
        f"vad_silence_ms = {config.stt.vad_silence_ms}",
        f"max_utterance_s = {_number(config.stt.max_utterance_s)}",
        f"manual_max_utterance_s = {_number(config.stt.manual_max_utterance_s)}",
        "",
        "[tts]",
        f"provider = {_quote(config.tts.provider)}",
        f"voice = {_quote(config.tts.voice)}",
        f"rate = {config.tts.rate}",
        f"volume = {_number(config.tts.volume)}",
        "",
        "[llm]",
        f"provider = {_quote(config.llm.provider)}",
        f"base_url = {_quote(config.llm.base_url)}",
        f"model = {_quote(config.llm.model)}",
        f"num_ctx = {config.llm.num_ctx}",
        f"keep_alive = {_quote(config.llm.keep_alive)}",
        f"temperature_chat = {_number(config.llm.temperature_chat)}",
        f"temperature_tools = {_number(config.llm.temperature_tools)}",
        f"history_turns = {config.llm.history_turns}",
        f"timeout_s = {_number(config.llm.timeout_s)}",
        "",
        "[weather]",
        f"default_city = {_quote(config.weather.default_city)}",
        f"cache_ttl_s = {config.weather.cache_ttl_s}",
        "",
        "[skills]",
        f"shell_enabled = {'true' if config.skills.shell_enabled else 'false'}",
        "",
        "[skills.aliases]",
    ]
    for alias, value in config.skills.aliases.items():
        lines.append(f"{_quote(alias)} = {_quote(value)}")
    lines.extend(
        [
            "",
            "[ui]",
            f"tray = {'true' if config.ui.tray else 'false'}",
            f"theme = {_quote(config.ui.theme)}",
            "",
            "[logging]",
            f"level = {_quote(config.logging.level)}",
            f"file = {_quote(config.logging.file)}",
            "",
        ]
    )
    return "\n".join(lines)


def write_config(path: Path, config: AppConfig) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_config(config), encoding="utf-8")


class SettingsDialog(QDialog):
    """Edits the values required by FR-13 and applies them immediately."""

    def __init__(
        self,
        config: AppConfig,
        *,
        on_apply: Callable[[], None] | None = None,
        tts: Any = None,
        voice_loop: Any = None,
        parent: Any = None,
    ) -> None:
        super().__init__(parent)
        self.setWindowTitle("Настройки Джарвиса")
        self.setMinimumWidth(420)
        self._config = config
        self._on_apply = on_apply
        self._tts = tts
        self._voice_loop = voice_loop

        self.model_edit = QLineEdit(config.llm.model)
        self.voice_edit = QLineEdit(config.tts.voice)
        self.hotkey_edit = QLineEdit(config.assistant.hotkey)
        self.manual_hotkey_edit = QLineEdit(config.assistant.manual_hotkey)
        self.city_edit = QLineEdit(config.weather.default_city)
        self.wake_check = QCheckBox("Слушать «hey jarvis» (постоянно)")
        self.wake_check.setChecked(config.assistant.wake_word_enabled)
        self.sensitivity_spin = QDoubleSpinBox()
        self.sensitivity_spin.setRange(0.05, 1.0)
        self.sensitivity_spin.setSingleStep(0.05)
        self.sensitivity_spin.setValue(config.assistant.sensitivity)
        self.rate_spin = QSpinBox()
        self.rate_spin.setRange(80, 350)
        self.rate_spin.setValue(config.tts.rate)

        form = QFormLayout()
        form.addRow("Модель Ollama:", self.model_edit)
        form.addRow("Голос (подстрока id):", self.voice_edit)
        form.addRow("Активация (hotkey):", self.hotkey_edit)
        form.addRow("Кнопка «Говорить» (hotkey):", self.manual_hotkey_edit)
        form.addRow("Город для погоды:", self.city_edit)
        form.addRow("", self.wake_check)
        form.addRow("Порог wake word:", self.sensitivity_spin)
        form.addRow("Скорость речи:", self.rate_spin)

        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Save | QDialogButtonBox.StandardButton.Cancel
        )
        save_button = buttons.button(QDialogButtonBox.StandardButton.Save)
        cancel_button = buttons.button(QDialogButtonBox.StandardButton.Cancel)
        if save_button is not None:
            save_button.setText("Сохранить")
        if cancel_button is not None:
            cancel_button.setText("Отмена")
        buttons.accepted.connect(self._save)
        buttons.rejected.connect(self.reject)

        layout = QVBoxLayout(self)
        layout.addLayout(form)
        layout.addWidget(buttons)

    def _save(self) -> None:
        self._config.llm.model = self.model_edit.text().strip()
        self._config.tts.voice = self.voice_edit.text().strip()
        self._config.assistant.hotkey = self.hotkey_edit.text().strip()
        self._config.assistant.manual_hotkey = self.manual_hotkey_edit.text().strip()
        self._config.assistant.wake_word_enabled = self.wake_check.isChecked()
        self._config.weather.default_city = self.city_edit.text().strip()
        self._config.assistant.sensitivity = float(self.sensitivity_spin.value())
        self._config.tts.rate = int(self.rate_spin.value())

        if self._tts is not None and hasattr(self._tts, "set_voice"):
            self._tts.set_voice(self._config.tts.voice)
            self._tts.set_rate(self._config.tts.rate)
        if self._voice_loop is not None:
            if hasattr(self._voice_loop, "set_threshold"):
                self._voice_loop.set_threshold(self._config.assistant.sensitivity)
            if hasattr(self._voice_loop, "set_hotkey"):
                self._voice_loop.set_hotkey(self._config.assistant.hotkey)
            if hasattr(self._voice_loop, "set_manual_hotkey"):
                self._voice_loop.set_manual_hotkey(self._config.assistant.manual_hotkey)
            if hasattr(self._voice_loop, "set_wake_word_enabled"):
                self._voice_loop.set_wake_word_enabled(
                    self._config.assistant.wake_word_enabled
                )

        if self._on_apply is not None:
            self._on_apply()
        self.accept()
